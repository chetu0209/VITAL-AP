`default_nettype none
`timescale 1ns / 1ps

module tb;

    reg clk;
    reg rst_n;
    reg ena;

    reg [7:0] ui_in;
    reg [7:0] uio_in;

    wire [7:0] uo_out;
    wire [7:0] uio_out;
    wire [7:0] uio_oe;


    tt_um_vital_ap dut (
        .ui_in   (ui_in),
        .uo_out  (uo_out),

        .uio_in  (uio_in),
        .uio_out (uio_out),
        .uio_oe  (uio_oe),

        .ena     (ena),
        .clk     (clk),
        .rst_n   (rst_n)
    );


    always #5 clk = ~clk;


    initial begin

        $dumpfile("tb.fst");
        $dumpvars(0, tb);

        clk = 1'b0;
        rst_n = 1'b0;
        ena = 1'b0;

        ui_in = 8'd0;

        // ----------------------------------------------------
        // Control:
        //
        // [1:0] sensitivity = 01
        // [2] prediction   = 1
        // [3] force        = 0
        // [4] value        = 1
        // [5] edge         = 1
        // [6] motion       = 1
        // ----------------------------------------------------

        uio_in = 8'b01110101;


        #30;

        rst_n = 1'b1;
        ena = 1'b1;


        // ----------------------------------------------------
        // Static region
        // ----------------------------------------------------

        ui_in = 8'd100;
        #20;

        ui_in = 8'd100;
        #20;

        ui_in = 8'd100;
        #20;


        // ----------------------------------------------------
        // Small change
        // ----------------------------------------------------

        ui_in = 8'd102;
        #20;


        // ----------------------------------------------------
        // Large edge
        // ----------------------------------------------------

        ui_in = 8'd200;
        #20;

        ui_in = 8'd20;
        #20;


        // ----------------------------------------------------
        // Motion sequence
        // ----------------------------------------------------

        ui_in = 8'd220;
        #20;

        ui_in = 8'd30;
        #20;

        ui_in = 8'd230;
        #20;

        ui_in = 8'd40;
        #20;


        // ----------------------------------------------------
        // Force update
        // ----------------------------------------------------

        uio_in[3] = 1'b1;

        ui_in = 8'd77;
        #20;

        uio_in[3] = 1'b0;


        // ----------------------------------------------------
        // Disable
        // ----------------------------------------------------

        ena = 1'b0;

        ui_in = 8'd150;
        #20;


        ena = 1'b1;


        #100;

        $finish;

    end

endmodule

`default_nettype wire
