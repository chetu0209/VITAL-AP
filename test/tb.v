`default_nettype none
`timescale 1ns / 1ps

module tb;

    reg clk;
    reg rst_n;
    reg ena;

    reg [7:0] ui_in;
    reg [7:0] uio_in;

    wire [7:0] uo_out;
    wire [7:0] uio_out;
    wire [7:0] uio_oe;

    tt_um_vital_ap dut (
        .ui_in   (ui_in),
        .uo_out  (uo_out),

        .uio_in  (uio_in),
        .uio_out (uio_out),
        .uio_oe  (uio_oe),

        .ena     (ena),
        .clk     (clk),
        .rst_n   (rst_n)
    );

    // ---------------------------------------------------------
    // CLOCK
    // ---------------------------------------------------------

    initial begin
        clk = 1'b0;
        forever #5 clk = ~clk;
    end


    // ---------------------------------------------------------
    // WAVEFORM
    // ---------------------------------------------------------

    initial begin
        $dumpfile("tb.fst");
        $dumpvars(0, tb);
    end


    // ---------------------------------------------------------
    // TEST
    // ---------------------------------------------------------

    initial begin

        rst_n  = 1'b0;
        ena    = 1'b0;
        ui_in  = 8'd0;

        // -----------------------------------------------------
        // Control bits
        //
        // [1:0] sensitivity
        // [2]   prediction
        // [3]   force
        // [4]   value aware
        // [5]   edge aware
        // [6]   motion aware
        // [7]   reserved
        // -----------------------------------------------------

        uio_in = 8'b01110101;


        // -----------------------------------------------------
        // RESET
        // -----------------------------------------------------

        #30;

        rst_n = 1'b1;
        ena   = 1'b1;


        // -----------------------------------------------------
        // STATIC IMAGE
        // -----------------------------------------------------

        ui_in = 8'd100;
        #20;

        ui_in = 8'd100;
        #20;

        ui_in = 8'd100;
        #20;

        ui_in = 8'd100;
        #20;


        // -----------------------------------------------------
        // SMALL VARIATIONS
        // -----------------------------------------------------

        ui_in = 8'd101;
        #20;

        ui_in = 8'd102;
        #20;

        ui_in = 8'd103;
        #20;

        ui_in = 8'd102;
        #20;


        // -----------------------------------------------------
        // IMAGE EDGE
        // -----------------------------------------------------

        ui_in = 8'd20;
        #20;

        ui_in = 8'd220;
        #20;

        ui_in = 8'd20;
        #20;

        ui_in = 8'd220;
        #20;


        // -----------------------------------------------------
        // MOTION
        // -----------------------------------------------------

        ui_in = 8'd30;
        #20;

        ui_in = 8'd230;
        #20;

        ui_in = 8'd40;
        #20;

        ui_in = 8'd240;
        #20;

        ui_in = 8'd50;
        #20;

        ui_in = 8'd200;
        #20;


        // -----------------------------------------------------
        // FORCE UPDATE
        // -----------------------------------------------------

        uio_in[3] = 1'b1;

        ui_in = 8'd77;
        #20;

        ui_in = 8'd77;
        #20;

        uio_in[3] = 1'b0;


        // -----------------------------------------------------
        // NORMAL ADAPTIVE MODE
        // -----------------------------------------------------

        ui_in = 8'd80;
        #20;

        ui_in = 8'd81;
        #20;

        ui_in = 8'd120;
        #20;

        ui_in = 8'd200;
        #20;


        // -----------------------------------------------------
        // DISABLE
        // -----------------------------------------------------

        ena = 1'b0;

        ui_in = 8'd150;
        #20;

        ui_in = 8'd200;
        #20;


        // -----------------------------------------------------
        // RE-ENABLE
        // -----------------------------------------------------

        ena = 1'b1;

        ui_in = 8'd200;
        #20;

        ui_in = 8'd100;
        #20;


        #50;

        $display("======================================");
        $display(" VITAL-AP RTL SIMULATION COMPLETE");
        $display("======================================");

        $finish;

    end

endmodule

`default_nettype wire
